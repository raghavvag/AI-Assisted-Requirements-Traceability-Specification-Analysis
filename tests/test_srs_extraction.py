GOLDEN = [
    ("ecommerce_srs_ieee.docx", "ecommerce_srs_ieee.expected.json"),
    ("banking_srs.docx", "banking_srs.expected.json"),
    ("messy_srs.docx", "messy_srs.expected.json"),
    ("untagged_srs.docx", "untagged_srs.expected.json"),
    ("ecommerce_srs_ieee.pdf", "ecommerce_srs_ieee_pdf.expected.json"),
]
COMPARED_FIELDS = ("id", "title", "text", "type", "priority")


def _expected(name: str) -> dict:
    return json.loads((FIXTURES / name).read_text(encoding="utf-8"))


def _project(reqs):
    return [{k: r[k] for k in COMPARED_FIELDS} for r in reqs]


def _docx_bytes(build) -> bytes:
    doc = Document()
    build(doc)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _write(tmp_path: Path, name: str, data: bytes) -> Path:
    p = tmp_path / name
    p.write_bytes(data)
    return p


