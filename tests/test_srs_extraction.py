class TestParity:
    @pytest.mark.parametrize("fixture,md", [
        ("ecommerce_srs_ieee.docx", ECOMMERCE_MD),
        ("ecommerce_srs_ieee.pdf", ECOMMERCE_MD),
        ("banking_srs.docx", BANKING_MD),
    ])
    def test_same_requirements_as_markdown(self, fixture, md):
        path = FIXTURES / fixture
        if not path.exists():
            pytest.skip(f"{fixture} not generated")
        doc = [(r["id"], r["title"], r["text"]) for r in extract_requirements(str(path))]
        txt = [(r["id"], r["title"], r["text"]) for r in extract_requirements(str(md))]
        assert doc == txt

    @pytest.mark.slow
    def test_docx_reproduces_published_metrics(self, semantic_embedder):
        """Full pipeline on store_v1: .docx must give exactly the .md metrics
        (Transformer F1 0.71, MAP unchanged)."""
        from src.evaluator import compute_map, compute_precision_recall_f1, load_ground_truth
        from src.parser import extract_endpoints
        from src.similarity import build_traceability_matrix, compute_similarity_matrix

        endpoints = extract_endpoints(str(ROOT / "data" / "api_specs" / "store_v1.json"))
        gt = load_ground_truth(str(ROOT / "data" / "ground_truth" / "traceability_labels.csv"))
        emb = semantic_embedder
        ep_emb = emb.encode_endpoints(endpoints)

        def metrics(srs_path):
            reqs = extract_requirements(str(srs_path))
            sim = compute_similarity_matrix(emb.encode_requirements(reqs), ep_emb)
            matrix = build_traceability_matrix(reqs, endpoints, sim, 0.55)
            prf = compute_precision_recall_f1(matrix, gt, reqs, endpoints, threshold=0.40)
            return prf, compute_map(matrix, gt, reqs)

        md_prf, md_map = metrics(ECOMMERCE_MD)
        docx_prf, docx_map = metrics(FIXTURES / "ecommerce_srs_ieee.docx")
        assert docx_map == pytest.approx(md_map, abs=1e-9)
        for key in md_prf:
            assert docx_prf[key] == pytest.approx(md_prf[key], abs=1e-9)
        # ...and both match the recorded baseline (scripts/snapshot_baseline_metrics.py)
        base = json.loads((ROOT / "tests" / "fixtures" / "baseline_metrics.json").read_text(encoding="utf-8"))
        tol, expected = base["tolerance"], base["transformer"]
        got = {k.lower().replace("-", "_").replace(" ", "_"): v for k, v in docx_prf.items()}
        for key in ("precision", "recall", "f1"):
            assert got[key] == pytest.approx(expected[key], abs=tol), key
        assert docx_map == pytest.approx(expected["map"], abs=tol)


