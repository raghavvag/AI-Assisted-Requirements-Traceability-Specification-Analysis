class TestDocxReader:
    def test_tracked_insertion_kept_deletion_dropped(self):
        def build(doc):
            p = doc.add_paragraph("Keep ")
            ins = OxmlElement("w:ins")
            ins.set(qn("w:id"), "1")
            r = OxmlElement("w:r")
            t = OxmlElement("w:t")
            t.text = "inserted"
            r.append(t)
            ins.append(r)
            p._p.append(ins)
            dele = OxmlElement("w:del")
            dele.set(qn("w:id"), "2")
            r2 = OxmlElement("w:r")
            dt = OxmlElement("w:delText")
            dt.text = " deleted"
            r2.append(dt)
            dele.append(r2)
            p._p.append(dele)
        doc = Document(io.BytesIO(_docx_bytes(build)))
        assert paragraph_text(doc.paragraphs[0]._p) == "Keep inserted"
        assert doc.paragraphs[0].text == "Keep "      # why we do not use python-docx's .text

    def test_content_control_unwrapped(self, tmp_path):
        def build(doc):
            p = doc.add_paragraph("FR-1: Inside a content control")
            sdt, content = OxmlElement("w:sdt"), OxmlElement("w:sdtContent")
            sdt.append(OxmlElement("w:sdtPr"))
            sdt.append(content)
            p._p.addprevious(sdt)
            content.append(p._p)
        blocks = read_docx(_write(tmp_path, "a.docx", _docx_bytes(build)))
        assert [b.text for b in blocks if isinstance(b, Paragraph)] == ["FR-1: Inside a content control"]

    def test_merged_cells_keep_columns_aligned(self, tmp_path):
        def build(doc):
            t = doc.add_table(rows=2, cols=3)
            for c, h in enumerate(["ID", "Title", "Description"]):
                t.rows[0].cells[c].text = h
            t.rows[1].cells[0].text = "FR-1"
            t.rows[1].cells[1].merge(t.rows[1].cells[2]).text = "Merged statement"
        table = next(b for b in read_docx(_write(tmp_path, "m.docx", _docx_bytes(build))) if isinstance(b, Table))
        assert table.rows[1] == ("FR-1", "Merged statement", "")

    def test_multi_paragraph_cell_and_header_flag(self, tmp_path):
        def build(doc):
            t = doc.add_table(rows=2, cols=2)
            t.rows[0].cells[0].text, t.rows[0].cells[1].text = "ID", "Description"
            t.rows[0]._tr.get_or_add_trPr().append(OxmlElement("w:tblHeader"))
            t.rows[1].cells[0].text = "FR-1"
            cell = t.rows[1].cells[1]
            cell.paragraphs[0].text = "Line one."
            cell.add_paragraph("Line two.")
        table = next(b for b in read_docx(_write(tmp_path, "h.docx", _docx_bytes(build))) if isinstance(b, Table))
        assert table.header_rows == 1
        assert table.rows[1][1] == "Line one.\nLine two."

    def test_single_cell_table_is_unwrapped(self, tmp_path):
        def build(doc):
            cell = doc.add_table(rows=1, cols=1).rows[0].cells[0]
            cell.paragraphs[0].text = "Callout text"
        blocks = read_docx(_write(tmp_path, "c.docx", _docx_bytes(build)))
        assert not any(isinstance(b, Table) for b in blocks)
        assert any(isinstance(b, Paragraph) and b.text == "Callout text" for b in blocks)

    def test_nested_table_emitted(self, tmp_path):
        def build(doc):
            outer = doc.add_table(rows=1, cols=2)
            outer.rows[0].cells[0].text = "Outer"
            inner = outer.rows[0].cells[1].add_table(rows=1, cols=2)
            inner.rows[0].cells[0].text, inner.rows[0].cells[1].text = "a", "b"
        tables = [b for b in read_docx(_write(tmp_path, "n.docx", _docx_bytes(build))) if isinstance(b, Table)]
        assert len(tables) == 2 and tables[1].nested and tables[1].rows[0] == ("a", "b")

    def test_heading_levels(self, tmp_path):
        def build(doc):
            doc.add_heading("Doc title", level=0)
            doc.add_heading("Chapter", level=1)
            p = doc.add_paragraph()
            p.add_run("3.2.1 Bold numbered line").bold = True
            doc.add_paragraph("3.2 Not bold so not a heading")
        blocks = read_docx(_write(tmp_path, "l.docx", _docx_bytes(build)))
        heads = [(b.level, b.text) for b in blocks if isinstance(b, Heading)]
        assert heads == [(0, "Doc title"), (1, "Chapter"), (3, "3.2.1 Bold numbered line")]


