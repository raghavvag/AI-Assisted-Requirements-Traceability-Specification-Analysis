class TestMarkdown:
    def test_legacy_path_unchanged(self):
        """The .md parser must stay byte-identical to the v1 regex parser."""
        for md in (ECOMMERCE_MD, BANKING_MD):
            v1 = legacy_extract(read_text_file(md))
            now = extract_requirements(str(md))
            assert [(r["id"], r["title"], r["text"]) for r in now] == [(r["id"], r["title"], r["text"]) for r in v1]

    def test_fallback_to_structured_markdown(self, tmp_path):
        md = tmp_path / "srs.md"
        md.write_text(
            "# Inventory SRS\n\n## 1 Glossary\n\nFR-9: Not a requirement, glossary is skipped\n\n"
            "## 2 Functional Requirements\n\n"
            "FR-1: Stock Lookup\nThe system shall return the stock level of a SKU.\n\n"
            "**FR-2** - Reorder Alerts\nThe system shall alert buyers when stock falls below the reorder point.\n\n"
            "| Req ID | Description | Priority |\n|---|---|---|\n"
            "| FR-3 | The system shall export stock levels as CSV. | Low |\n",
            encoding="utf-8",
        )
        reqs, report = extract_requirements_with_report(md)
        assert [r["id"] for r in reqs] == ["FR-1", "FR-2", "FR-3"]
        assert reqs[0]["text"] == "Stock Lookup. The system shall return the stock level of a SKU."
        assert reqs[1]["title"] == "Reorder Alerts"
        assert reqs[2]["priority"] == "Low" and reqs[2]["strategy"] == "table"
        assert report.format == "markdown"

    def test_txt_cp1252(self, tmp_path):
        p = tmp_path / "srs.txt"
        p.write_bytes("REQ-01: Caf\xe9 Ordering\nThe system must accept \x93orders\x94.\n".encode("latin-1"))
        reqs = extract_requirements(str(p))
        assert reqs[0]["title"] == "Café Ordering"

    def test_no_requirements_raises_with_report(self, tmp_path):
        p = tmp_path / "notes.md"
        p.write_text("# Meeting notes\n\nWe talked about the roadmap.\n", encoding="utf-8")
        with pytest.raises(NoRequirementsFoundError) as exc:
            extract_requirements_with_report(p)
        assert isinstance(exc.value, ValueError)
        assert exc.value.report is not None and "No requirements" in str(exc.value)


