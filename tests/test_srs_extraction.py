class TestTagMatcher:
    tags = TagMatcher(DEFAULT_ID_PATTERN)

    @pytest.mark.parametrize("text,expected", [
        ("FR-1: Login", ("FR-1", "Login")),
        ("FR1 - Login", ("FR1", "Login")),
        ("REQ-04. The system must refund", ("REQ-04", "The system must refund")),
        ("[NFR-2] Encryption", ("NFR-2", "Encryption")),
        ("(FR-3) Export", ("FR-3", "Export")),
        ("FR-5.1\tProfile", ("FR-5.1", "Profile")),
        ("BNK-REQ-01: Authentication", ("BNK-REQ-01", "Authentication")),
        ("FR-2 The system shall lock accounts", ("FR-2", "The system shall lock accounts")),
        ("FR 3 - Password Reset", ("FR 3", "Password Reset")),
        ("FR-7", ("FR-7", "")),
    ])
    def test_paragraph_tags(self, text, expected):
        assert self.tags.match_paragraph(text) == expected

    @pytest.mark.parametrize("text", [
        "See REQ-02 for details.",
        "REQ-02 requires a session id.",
        "The FR-1 requirement is covered.",
        "FRONTEND-1: not an id keyword",
        "Requirement REQ-3 applies.",
    ])
    def test_not_tags(self, text):
        assert self.tags.match_paragraph(text) is None

    def test_heading_with_numbering(self):
        assert self.tags.match_heading("3.2.1 FR-1 User Login") == ("FR-1", "User Login")

    def test_custom_pattern(self, tmp_path):
        def build(doc):
            doc.add_heading("Capabilities", level=1)
            doc.add_paragraph("CAP-001: Search")
            doc.add_paragraph("The portal shall support full-text search.")
        p = _write(tmp_path, "cap.docx", _docx_bytes(build))
        # Default pattern does not know "CAP-": only the shall-statement fallback fires.
        default, _ = extract_requirements_with_report(p)
        assert default[0]["id_source"] == "generated"
        reqs, _ = extract_requirements_with_report(p, ExtractionOptions(id_pattern=r"CAP-\d{3}"))
        assert reqs[0]["id"] == "CAP-001" and reqs[0]["title"] == "Search"


class TestTables:
    def _doc(self, tmp_path, header, rows, name="t.docx"):
        def build(doc):
            doc.add_heading("Functional Requirements", level=1)
            n = 1 + len(rows) if header else len(rows)
            t = doc.add_table(rows=n, cols=len(rows[0]))
            all_rows = ([header] if header else []) + rows
            for r, vals in enumerate(all_rows):
                for c, v in enumerate(vals):
                    t.rows[r].cells[c].text = v
        return _write(tmp_path, name, _docx_bytes(build))

    def test_header_aliases(self, tmp_path):
        p = self._doc(tmp_path, ["Req. ID", "Requirement Description", "MoSCoW", "Fit Criterion"],
                      [["SR-12", "The system shall print receipts.", "Must", "Receipt within 2 s."]])
        r = extract_requirements(str(p))[0]
        assert (r["id"], r["priority"]) == ("SR-12", "Must")
        assert r["text"] == "The system shall print receipts. Acceptance criteria: Receipt within 2 s."

    def test_headerless_table(self, tmp_path):
        p = self._doc(tmp_path, None, [["FR-1", "The system shall log in users."],
                                       ["FR-2", "The system shall log out users."]])
        assert [r["id"] for r in extract_requirements(str(p))] == ["FR-1", "FR-2"]

    def test_numeric_ids_get_prefix(self, tmp_path):
        p = self._doc(tmp_path, ["No.", "Requirement"], [["1", "The system shall archive orders."]])
        assert extract_requirements(str(p))[0]["id"] == "REQ-1"

    def test_non_requirement_table_ignored(self, tmp_path):
        p = self._doc(tmp_path, ["Version", "Date", "Description"], [["1.0", "2026-01-01", "First release"]])
        with pytest.raises(NoRequirementsFoundError):
            extract_requirements_with_report(p)


