class TestErrors:
    def test_missing_file(self):
        with pytest.raises(FileNotFoundError):
            extract_requirements("does/not/exist.docx")

    @pytest.mark.parametrize("ext", [".doc", ".docm", ".rtf", ".odt", ".xlsx"])
    def test_unsupported_extensions(self, tmp_path, ext):
        p = _write(tmp_path, f"srs{ext}", b"whatever")
        with pytest.raises(UnsupportedFormatError):
            extract_requirements_with_report(p)

    def test_scanned_pdf(self):
        with pytest.raises(ScannedPdfError):
            extract_requirements_with_report(FIXTURES / "scanned.pdf")

    def test_not_a_zip(self, tmp_path):
        p = _write(tmp_path, "srs.docx", b"this is not a zip")
        with pytest.raises(InvalidDocumentError):
            extract_requirements_with_report(p)

    def test_zip_without_document_xml(self, tmp_path):
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w") as z:
            z.writestr("hello.txt", "hi")
        p = _write(tmp_path, "srs.docx", buf.getvalue())
        with pytest.raises(InvalidDocumentError):
            extract_requirements_with_report(p)

    def test_macro_enabled_package_rejected(self, tmp_path):
        src = (FIXTURES / "messy_srs.docx").read_bytes()
        buf = io.BytesIO()
        with zipfile.ZipFile(io.BytesIO(src)) as zin, zipfile.ZipFile(buf, "w") as zout:
            for item in zin.infolist():
                zout.writestr(item, zin.read(item.filename))
            zout.writestr("word/vbaProject.bin", b"\x00" * 10)
        p = _write(tmp_path, "srs.docx", buf.getvalue())
        with pytest.raises(UnsupportedFormatError):
            extract_requirements_with_report(p)

    def test_zip_bomb_guard(self):
        with pytest.raises(InvalidDocumentError, match="decompressed"):
            guard_docx_archive(FIXTURES / "messy_srs.docx", max_uncompressed_bytes=1000)

    def test_errors_are_value_errors(self):
        assert issubclass(SRSExtractionError, ValueError)


