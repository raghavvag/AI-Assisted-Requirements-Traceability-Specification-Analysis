class TestGoldenFixtures:
    @pytest.mark.parametrize("fixture,golden", GOLDEN)
    def test_matches_golden(self, fixture, golden):
        path = FIXTURES / fixture
        if not path.exists():
            pytest.skip(f"{fixture} not generated (run scripts/build_srs_fixtures.py --pdf on Windows+Word)")
        reqs, report = extract_requirements_with_report(path)
        assert _project(reqs) == _expected(golden)["requirements"]
        assert report.n_requirements == len(reqs)
        assert sum(report.by_strategy.values()) == len(reqs)

    @pytest.mark.parametrize("fixture,golden", GOLDEN)
    def test_no_boilerplate_leaks(self, fixture, golden):
        path = FIXTURES / fixture
        if not path.exists():
            pytest.skip(f"{fixture} not generated")
        reqs, _ = extract_requirements_with_report(path)
        blob = " ".join(f"{r['title']} {r['text']}" for r in reqs)
        for needle in _expected(golden).get("must_not_contain", []):
            assert needle not in blob, f"boilerplate {needle!r} leaked into requirements"

    def test_messy_duplicate_reported(self):
        _, report = extract_requirements_with_report(FIXTURES / "messy_srs.docx")
        assert report.duplicates == ["FR-2"]
        assert any("Duplicate ID FR-2" in w for w in report.warnings)

    def test_messy_report_counts_noise(self):
        _, report = extract_requirements_with_report(FIXTURES / "messy_srs.docx")
        assert report.skipped["repeated_header_row"] == 1
        assert report.skipped["layout_table_unwrapped"] == 1
        assert any(k.startswith("blocklisted_section:Appendix") for k in report.skipped)

    def test_ieee_report_counts_noise(self):
        _, report = extract_requirements_with_report(FIXTURES / "ecommerce_srs_ieee.docx")
        assert report.skipped["toc"] >= 1
        assert report.skipped["image"] == 1
        assert report.skipped["caption"] == 2
        assert report.by_strategy == {"table": 6, "tagged": 4}

    def test_source_locator_and_metadata(self):
        reqs, _ = extract_requirements_with_report(FIXTURES / "ecommerce_srs_ieee.docx")
        first, last = reqs[0], reqs[-1]
        assert first["source"] == {"file": "ecommerce_srs_ieee.docx", "format": "docx", "locator": "table 3 / row 2"}
        assert first["strategy"] == "table" and first["priority"] == "High"
        assert first["section"] == "3 Specific Requirements > 3.1 Core Functional Requirements"
        assert last["strategy"] == "tagged" and last["source"]["locator"].startswith("heading")

    def test_include_nfr_false(self):
        reqs, report = extract_requirements_with_report(
            FIXTURES / "messy_srs.docx", ExtractionOptions(include_nfr=False))
        assert all(not r["id"].startswith("NFR") for r in reqs)
        assert report.skipped["non_functional_excluded"] == 2

    def test_untagged_ids_are_generated(self):
        reqs, report = extract_requirements_with_report(FIXTURES / "untagged_srs.docx")
        assert all(r["id_source"] == "generated" for r in reqs)
        assert report.warnings


